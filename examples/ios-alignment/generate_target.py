#!/usr/bin/env python3
"""Generate the public 3x3 tag36h11 board, IDs 0..8; no captured inputs."""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[2]
def generate():
 source=(ROOT/'.deps/apriltag/tag36h11.c').read_text()
 codes=[int(x,16) for x in re.findall(r'0x([0-9a-f]+)UL',source)][:9]
 coords={axis:{int(i):int(v) for i,v in re.findall(r'tf->bit_'+axis+r'\[(\d+)\] = (\d+);',source)} for axis in ('x','y')}
 assert len(codes)==9 and len(coords['x'])==36
 parts=['<svg xmlns="http://www.w3.org/2000/svg" width="210mm" height="297mm" viewBox="0 0 210 297">','<!-- Generated by generate_target.py. AprilTag family: BSD-2-Clause; see Adapter/APRILTAG-LICENSE.txt. -->','<rect width="210" height="297" fill="white"/>','<text x="15" y="18" font-family="sans-serif" font-size="5">Camera alignment — print at 100% on A4</text>']
 for tag,code in enumerate(codes):
  ox,oy=15+(tag%3)*65,35+(tag//3)*65
  parts.append(f'<rect x="{ox}" y="{oy}" width="50" height="50" fill="black"/>')
  for bit in range(36):
   if code & (1<<(35-bit)):
    x,y=ox+coords['x'][bit]*6.25,oy+coords['y'][bit]*6.25
    parts.append(f'<rect x="{x}" y="{y}" width="6.25" height="6.25" fill="white"/>')
 parts+=['<text x="15" y="238" font-family="sans-serif" font-size="4">Each black border: 50 mm. Pitch: 65 mm. Keep the board flat.</text>','<text x="15" y="247" font-family="sans-serif" font-size="4">No gravity reference: camera-to-camera alignment only.</text>','<path d="M15 265h50m-50 -2v4m50 -4v4" stroke="black" fill="none"/>','<text x="15" y="275" font-family="sans-serif" font-size="4">Check this line measures 50 mm.</text>','</svg>']
 return '\n'.join(parts)+'\n'
if __name__=='__main__':(ROOT/'examples/ios-alignment/target.svg').write_text(generate())
